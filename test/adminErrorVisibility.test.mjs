import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('real admin diagnostics, including history, are visible without counting admin usage or exposing the dashboard', async context => {
  const db = new PGlite(); context.after(() => db.close());
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY, created_at timestamptz DEFAULT now(), email_confirmed_at timestamptz);
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    CREATE TABLE public.user_roles(user_id uuid, role text);
    CREATE FUNCTION public.has_role(_user_id uuid,_role text) RETURNS boolean LANGUAGE sql SECURITY DEFINER AS $$ SELECT EXISTS(SELECT 1 FROM public.user_roles WHERE user_id=_user_id AND role=_role) $$;
    GRANT USAGE ON SCHEMA auth TO authenticated; GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated;
    CREATE TABLE public.boulders(id uuid PRIMARY KEY,name text);
    CREATE TABLE public.notifications(id uuid PRIMARY KEY,user_id uuid,type text,read boolean DEFAULT false,dismissed_at timestamptz);
    CREATE TABLE public.boulder_ticks(id uuid PRIMARY KEY,user_id uuid,status text,attempt_count integer,is_favorite boolean DEFAULT false,is_project boolean DEFAULT false);`);
  await db.exec(await readFile(new URL('../supabase/migrations/20261017203000_beta_launch_monitoring.sql', import.meta.url), 'utf8'));
  const admin = crypto.randomUUID(), user = crypto.randomUUID(), installation = crypto.randomUUID(), session = crypto.randomUUID();
  await db.query('INSERT INTO auth.users(id) VALUES($1),($2)', [admin, user]);
  await db.query("INSERT INTO public.user_roles VALUES($1,'admin')", [admin]);
  const scalar = async (sql, args = []) => (await db.query(sql, args)).rows[0].value;
  const event = (name = 'app_error', channel = 'production') => ({ event_id: crypto.randomUUID(), installation_id: installation, session_id: session, name, channel, occurred_at: new Date().toISOString(), platform: 'web', app_version: '1.0.255', release: 'kws-beta-app@1.0.255+fixture', consent: 'granted', boulder_id: null, props: { code: 'AdminNetworkError', message: 'App-Daten konnten nicht geladen werden' } });
  const ingest = item => scalar('SELECT public.kws_ingest_monitoring_events($1::jsonb,$2::uuid) AS value', [JSON.stringify([item]), admin]);
  const historical = event(), synthetic = event('app_error', 'test');
  await ingest(historical); await ingest(synthetic); await ingest(event('session_start'));
  const migration = await readFile(new URL('../supabase/migrations/20261021130000_admin_error_visibility.sql', import.meta.url), 'utf8');
  await db.exec(migration); await db.exec(migration);
  assert.equal(await scalar('SELECT excluded AS value FROM public.monitoring_events WHERE event_id=$1', [historical.event_id]), false);
  assert.equal(await scalar('SELECT excluded AS value FROM public.monitoring_events WHERE event_id=$1', [synthetic.event_id]), true);
  const fresh = event('app_error', 'testflight'); await ingest(fresh);
  const previousUsage = await scalar('SELECT last_usage_at AS value FROM public.monitoring_sessions WHERE id=$1', [session]);
  const anonymous = { ...event(), consent: 'denied' };
  await scalar('SELECT public.kws_ingest_monitoring_events($1::jsonb,NULL) AS value', [JSON.stringify([anonymous])]);
  assert.equal(await scalar('SELECT user_id AS value FROM public.monitoring_sessions WHERE id=$1', [session]), admin);
  assert.equal((await scalar('SELECT last_usage_at AS value FROM public.monitoring_sessions WHERE id=$1', [session])).toISOString(), previousUsage.toISOString());
  await ingest(event('screen_view')); await ingest(event('app_error', 'development'));
  assert.equal(await scalar('SELECT excluded AS value FROM public.monitoring_events WHERE event_id=$1', [fresh.event_id]), false);
  assert.equal(await scalar('SELECT bool_and(excluded) AS value FROM public.monitoring_sessions'), true);
  assert.equal(await scalar('SELECT bool_and(excluded) AS value FROM public.monitoring_installations'), true);
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [admin]);
  await db.exec('SET ROLE authenticated');
  const dashboard = await scalar('SELECT public.kws_monitoring_dashboard() AS value');
  assert.equal(dashboard.summary.sessions, 0); assert.equal(dashboard.summary.active_devices, 0);
  assert.equal(dashboard.summary.errors, 3); assert.equal(dashboard.issues[0].occurrences, 3);
  assert.equal((await scalar('SELECT public.kws_monitoring_issue_events($1) AS value', [dashboard.issues[0].fingerprint])).length, 3);
  await db.exec('RESET ROLE');
  assert.equal(await scalar('SELECT count(*)::integer AS value FROM public.monitoring_alert_queue'), 0);
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [user]);
  await db.exec('SET ROLE authenticated');
  await assert.rejects(() => scalar('SELECT public.kws_monitoring_dashboard() AS value'), /Administrator required/);
  await db.exec('RESET ROLE; SET ROLE anon');
  await assert.rejects(() => scalar('SELECT public.kws_monitoring_dashboard() AS value'), /permission denied/);
  await assert.rejects(() => scalar('SELECT count(*) AS value FROM public.monitoring_events'), /permission denied/);
});
