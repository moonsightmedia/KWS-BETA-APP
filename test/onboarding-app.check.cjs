const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 375, height: 812 } });
  const page = await context.newPage();
  const errors = [];
  const writes = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (['POST', 'PATCH', 'DELETE'].includes(request.method()) && /boulder_ticks|boulder_tracking_sessions/.test(request.url())) writes.push(request.url());
  });
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await page.goto('http://127.0.0.1:5220/');
  await page.locator('[data-coachmark=discover]').waitFor({ state: 'visible' });
  assert.equal(new URL(page.url()).pathname, '/guest');
  assert.equal(await page.getByRole('complementary', {name: 'Nutzungsstatistik auswählen'}).count(), 0);
  await page.getByRole('button', { name: 'Überspringen', exact: true }).click();
  await page.getByRole('complementary', {name: 'Nutzungsstatistik auswählen'}).waitFor({state:'visible'});
  assert.equal(await page.evaluate(() => localStorage.getItem('kws-onboarding-v1')), 'seen');
  await page.reload();
  await page.getByRole('button', { name: 'Einführung ansehen', exact: true }).waitFor();
  assert.equal(await page.locator('[data-coachmark]').count(), 0);
  await page.getByRole('button', { name: 'Filter', exact: true }).click();
  await page.getByRole('button', { name: 'Grad 2', exact: true }).click();
  await page.getByRole('button', { name: 'Filter schließen', exact: true }).click();
  const count = await page.locator('[data-onboarding=filter-results]').innerText();
  const originalCard = await page.locator('[data-onboarding=discover]').elementHandle();
  await page.getByRole('button', { name: 'Einführung ansehen', exact: true }).click();
  await page.locator('[data-coachmark=discover]').getByRole('button', { name: 'Boulder öffnen' }).click();
  await page.locator('[data-coachmark=beta]').getByRole('button', { name: 'Weiter zu den Filtern' }).click();
  await page.locator('[data-coachmark=filter]').waitFor({ state: 'visible' });
  assert.equal(await originalCard.evaluate(element => element.isConnected), true);
  assert.equal(await page.locator('[data-onboarding=filter-results]').innerText(), count);
  await page.locator('[data-coachmark=filter]').getByRole('button', { name: 'Einführung schließen' }).click();
  await page.goto('http://127.0.0.1:5220/app/register');
  await page.locator('#signup-email').waitFor({ state: 'visible' });
  assert.equal(await page.locator('[data-coachmark]').count(), 0);
  assert.deepEqual(writes, []);
  assert.deepEqual(errors, []);
  console.log('PASS real app: first launch, completion across reload, retained filter/card, direct registration, no personal writes');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
